import { artifactSizeLimits } from "@/lib/artifact-limits";
import { fileLimits, formatBytes } from "@/lib/files/config";
import { pageBatchLimits } from "@/lib/page-files/publish-rules";
import { hiddenAllowanceWords } from "@/lib/page-files/renew-rules";
import { pageFileLimits, pageFileTypesHint } from "@/lib/page-files/rules";
import { pageTokenLimits } from "@/lib/page-files/token";
import { pageScriptHosts } from "@/lib/page-host/rules";

const hostNames = pageScriptHosts.map((host) => host.replace("https://", ""));

/** "10 to 15 minutes": how long a page's files address works, from the token's own limits. */
const addressLife = `${String((pageTokenLimits.lifeSeconds - pageTokenLimits.stepSeconds) / 60)} to ${String(pageTokenLimits.lifeSeconds / 60)} minutes`;

/**
 * The guide agents read before they write an HTML artifact
 * (artifacts_formats_guide with kind "html"). Every rule here is what the
 * sandbox enforces (src/lib/page-host/rules.ts): the hosts come from the
 * same list as the page's Content-Security-Policy.
 */
export function buildHtmlGuide(): string {
  return [
    "HTML (html): a full web page that runs in a sandbox. Use it for anything visual or interactive: mockups of websites and apps, prototypes, dashboards, reports, explainers, small tools.",
    "",
    "The document",
    "- One HTML document: the artifact's content, which is the page, or the first page of a site (index.html). It must start with <!doctype html>.",
    "- For a small page, put the CSS in <style> and the JavaScript in <script>, inside the document: one call saves it all.",
    `- The document is at most ${artifactSizeLimits.maxContentBytes.toLocaleString("en-US")} bytes. Put anything heavy (images, data, libraries you bundled, large scripts and styles) in page files.`,
    '- Add <meta name="viewport" content="width=device-width, initial-scale=1">, a <title>, and lang on <html>.',
    "",
    "What the page may load",
    `- Scripts, styles, fonts, images, and data may load only from: ${hostNames.join(", ")}. Styles and fonts may also load from fonts.googleapis.com and fonts.gstatic.com.`,
    "- Pin a version, for example https://cdn.jsdelivr.net/npm/chart.js@4.4.1/dist/chart.umd.min.js. For utility classes, https://cdn.tailwindcss.com works.",
    '- ES modules work: <script type="module"> with imports from https://esm.sh/.',
    "- Every other request is refused: no fetch or XMLHttpRequest to your own API or any other site, no images or media from other sites, no analytics. Put the data in the page, or in a page file.",
    "- Small images of your own can be inline SVG or data: URIs. Larger ones are page files.",
    "",
    "Page files",
    '- A page can have its own files and load them by relative path, as on any website: <link rel="stylesheet" href="css/site.css">, <script type="module" src="js/app.js"> (and its own import "./chart.js"), <img src="img/logo.png">, url(../img/bg.png) in a stylesheet, fetch("data.json").',
    '- Paths are relative to the page, which is index.html. Do not start a path with / and do not use "..": write css/site.css, never /css/site.css.',
    "- A path is matched exactly, letter case included: a link to Css/Site.css does not find css/site.css, and the page gets a 404 for it. Use lowercase paths, and write each link exactly as the file's pagePath.",
    `- To add or change many at once, such as a whole site: page_files_request_uploads with the artifact and every file's path and exact size (up to ${String(pageBatchLimits.maxUploadsPerRequest)} in a call; for more, call again for the rest). It checks the whole set first, and its result gives each file's path, fileId, PUT url, and headers. PUT each file, then page_files_publish once with all the fileIds (up to ${String(pageBatchLimits.maxFilesPerPublish)}). The files go in together as one version, or not at all: if any file is at fault, nothing changes and the error names every file to fix.`,
    "- One page_files_publish call can bring the page's files to a new state: an upload at a new path is added, an upload at a path the page already has replaces that file, and each path in remove is deleted. The page loads the new files at once; the document does not need to be saved again.",
    `- For one or two files, the single-file tools work too: files_request_upload with pagePath (for example "css/site.css") and the exact size, PUT the bytes, files_finalize, then files_attach to the artifact. To change one: upload again with the same pagePath, then files_replace with the file's id. To remove one: files_delete.`,
    `- A page file may be ${pageFileTypesHint}. Its type comes from its extension.`,
    `- At most ${String(pageFileLimits.maxFiles)} page files and ${formatBytes(pageFileLimits.maxTotalBytes)} in all per artifact, and ${formatBytes(fileLimits.maxBytes)} per file.`,
    "",
    "A site of several pages",
    "- index.html is the artifact's content: the first page. Every other page is a page file whose path ends in .html, such as about.html or docs/guide.html. Upload it like any page file, in the same page_files_request_uploads set as the rest of the site.",
    '- Link the pages with ordinary relative links: <a href="about.html">About</a>, and from docs/guide.html back to the first page with ../index.html. A link, or location.href = "about.html" in a script, opens the page in the same frame, and the browser\'s Back and Forward move between the pages.',
    "- Every page follows the same rules as the first: the same hosts, the same refusals, and its own files by relative path from its own folder (from docs/guide.html, guide.css is docs/guide.css and ../css/site.css is css/site.css).",
    "- Start every page with <!doctype html>. A page without it is not refused, but the browser draws it in quirks mode, as it would any page without one.",
    "- Each page starts afresh when it opens. What one page keeps for another goes in localStorage or sessionStorage, which every page of the artifact shares.",
    "- A link to a page that has no file shows a line that says so, with a link to the first page. Name pages in lowercase and end them in .html, never .htm; index.html at the top is the artifact's own.",
    "- A folder's address is not a page: docs/ does not open docs/index.html. Link to docs/index.html itself. A link to a folder, or to another site, leaves the frame, and the frame is closed.",
    "",
    "What goes in the document, and what goes in files",
    "- Keep in the document: the markup, and the CSS and JavaScript of a small page. A page with no files saves in one call and is easy to read and change.",
    `- Put in page files: images, fonts, data, libraries you bundled, and any stylesheet or script too long to resend. Every change to the document sends the whole document again (artifacts_update), and the document is at most ${artifactSizeLimits.maxContentBytes.toLocaleString("en-US")} bytes. A page file changes by itself.`,
    "- A good split for a site: index markup in the document, css/site.css, js/app.js as a module that imports its parts, img/ for pictures, data/ for JSON the page fetches.",
    "",
    "A page that stays open",
    `- A page's files load under an address that ends after ${addressLife}. While the page's tab is visible, and for ${hiddenAllowanceWords()} after it was hidden, it gets the next address before that, without loading again, so a page left open keeps working, music and video in a background tab included.`,
    '- What follows the new address: fetch("data.json"), elements the page adds later (an <img>, a <script>, a <link>), and anything resolved against the document, such as new URL("js/chart.js", document.baseURI).',
    "- What does not: a module that already loaded keeps the address it loaded from for its own later relative import() and for import.meta.url, and a stylesheet file keeps it for its own url(...). After the first address ended, those are refused until the reader loads the page again.",
    '- So import what a module needs when it starts. For a part you load later, resolve it from the document: import(new URL("js/chart.js", document.baseURI)).',
    `- A tab that stayed hidden for more than ${hiddenAllowanceWords()} stops asking, and gets its next address when it is shown again. A file asked for after that, before the tab is shown, is refused; ask again once the tab is visible.`,
    "- Files a publish removed stop loading for every reader at once.",
    "- Readers of a shared page see the files that were approved with it, like the page itself.",
    "",
    "What the page cannot do",
    "- Submit a form to a server. Handle input with JavaScript in the page.",
    "- Show another page in an iframe, or navigate the tab it is shown in.",
    '- Open another site in its own place. Write links to other sites as <a href="…" target="_blank" rel="noopener">, so they open in a new tab.',
    "- Read anything of artifacts.space, of the reader, or of another artifact.",
    "",
    "What works",
    "- Inline scripts and styles, canvas, SVG, CSS animation, web workers from a blob: URL or a page file.",
    "- localStorage and sessionStorage. They belong to this artifact and to the reader's browser: another reader, or the same reader in another browser, starts empty. Wrap each use in try/catch.",
    "",
    "How it is shown",
    "- People see the running page in a frame on the artifact page: as wide as the page, about 80% of the window's height. The page scrolls inside the frame.",
    "- Make the layout work from 360 px wide to a desktop window.",
    "- The page sets its own colors. Without them it is black text on white. Check that text passes WCAG AA contrast.",
    "- Escape leaves full screen. A page that uses Escape itself does the work in its own keydown listener (closes its menu, clears its search field) and calls event.preventDefault() there, so the key stays with it. preventDefault() also stops what the browser would have done, such as a search field clearing itself, so the listener does that work. A dialog opened with showModal(), or an open popover that is not popover=\"manual\", in the page's own document (not inside a shadow root) keeps its Escape without any of this; a dialog opened with show() or the open attribute does not.",
    "- Editors change the page through View source, or through you.",
    "",
    "Saving",
    '- artifacts_create with kind "html" and the document as content. To change it, send the whole new document with artifacts_update and the baseVersion you read.',
    '- artifacts_validate with kind "html" checks that the document starts as a page. It does not run it: read your scripts for errors before you save.',
    '- After you save, artifacts_page_image shows the page running, as a picture: check the layout and that it starts, fix what is wrong, and look again. Pass width 390 and height 844 to see it on a phone.',
    "",
    "Example",
    "<!doctype html>",
    '<html lang="en">',
    "<head>",
    '  <meta charset="utf-8">',
    '  <meta name="viewport" content="width=device-width, initial-scale=1">',
    "  <title>Signups this week</title>",
    "  <style>",
    "    body { margin: 0; padding: 2rem; font: 16px/1.5 system-ui, sans-serif; color: #1a1a1a; background: #fafaf9; }",
    "    .bars { display: flex; align-items: end; gap: 0.5rem; height: 12rem; }",
    "    .bars div { flex: 1; background: #2563eb; border-radius: 4px 4px 0 0; }",
    "  </style>",
    "</head>",
    "<body>",
    "  <h1>Signups this week</h1>",
    '  <div class="bars" id="bars" role="img" aria-label="Signups per day, Monday to Friday"></div>',
    "  <script>",
    "    const perDay = [12, 18, 9, 24, 30];",
    "    const top = Math.max(...perDay);",
    '    document.getElementById("bars").append(...perDay.map((count) => {',
    '      const bar = document.createElement("div");',
    '      bar.style.height = (count / top) * 100 + "%";',
    "      bar.title = String(count);",
    "      return bar;",
    "    }));",
    "  </script>",
    "</body>",
    "</html>",
  ].join("\n");
}
